// Command genemoji regenerates emoji_table.go from the Unicode emoji-data.txt
// property file. Run via `go generate ./...` from the repo root.
//
// It emits the set of base codepoints that default to emoji (color) presentation.
// The rule (see clusterIsEmoji) is:
//
//		Emoji_Presentation  ∧  codepoint ≥ U+2300  ∧  ¬Emoji_Component
//
//	  - Emoji_Presentation: the codepoints Unicode renders as emoji *by default*.
//	    This is narrower than the Emoji property: default-text symbols such as
//	    U+2733 ✳ (eight-spoked asterisk), ❄ ❤ ☀ ✂ ➡ carry Emoji but not
//	    Emoji_Presentation — bare, they must render as the monochrome text glyph
//	    (matching Core Text / Ghostty); only an explicit VS16 (U+FE0F) requests
//	    the color form, which clusterIsEmoji handles via its combiner case. Plain
//	    non-emoji symbols (alchemical, chess, cards, arrows, box-drawing) carry
//	    neither property and keep their text-font fallback instead of being forced
//	    down the color-only path and rendering as the base font's .notdef box.
//	  - ≥ U+2300: the property's lowest member is U+231A, so this is a free
//	    fast-path floor (see isEmojiBase) — it excludes nothing.
//	  - ¬Emoji_Component: drops skin-tone modifiers, regional indicators, and hair
//	    components; those are handled by dedicated cases in clusterIsEmoji or only
//	    appear appended to a base, and never stand alone as an emoji base.
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

// unicodeVersion pins the UCD release for reproducible output. Bump it (and
// re-run go generate) to adopt newer emoji.
const unicodeVersion = "17.0.0"

const dataURL = "https://www.unicode.org/Public/" + unicodeVersion +
	"/ucd/emoji/emoji-data.txt"

const outFile = "emoji_table.go"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "genemoji:", err)
		os.Exit(1)
	}
}

func run() error {
	epres, err := fetchProperty("Emoji_Presentation")
	if err != nil {
		return err
	}
	comp, err := fetchProperty("Emoji_Component")
	if err != nil {
		return err
	}

	var cps []rune
	for r := range epres {
		if r >= 0x2300 && !comp[r] {
			cps = append(cps, r)
		}
	}
	sort.Slice(cps, func(i, j int) bool { return cps[i] < cps[j] })

	// Coalesce contiguous codepoints into inclusive ranges.
	type rng struct{ lo, hi rune }
	var ranges []rng
	for _, r := range cps {
		if n := len(ranges); n > 0 && r == ranges[n-1].hi+1 {
			ranges[n-1].hi = r
		} else {
			ranges = append(ranges, rng{r, r})
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/genemoji; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: Unicode emoji-data.txt, version %s.\n", unicodeVersion)
	fmt.Fprintf(&b, "// Rule: Emoji_Presentation ∧ (codepoint ≥ U+2300) ∧ ¬Emoji_Component.\n")
	fmt.Fprintf(&b, "// See internal/genemoji and clusterIsEmoji for the rationale.\n\n")
	fmt.Fprintf(&b, "package glyph\n\n")
	fmt.Fprintf(&b, "// emojiBaseRanges are the inclusive codepoint ranges whose base\n")
	fmt.Fprintf(&b, "// character warrants a color-emoji font. Sorted ascending and\n")
	fmt.Fprintf(&b, "// non-overlapping — required by isEmojiBase's binary search.\n")
	fmt.Fprintf(&b, "var emojiBaseRanges = [...][2]rune{\n")
	for _, rr := range ranges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", rr.lo, rr.hi)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("gofmt: %w", err)
	}
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s: %d codepoints in %d ranges (Unicode %s)\n",
		outFile, len(cps), len(ranges), unicodeVersion)
	return nil
}

// fetchProperty downloads emoji-data.txt and returns the codepoints carrying
// the given binary property (e.g. "Emoji", "Emoji_Component").
func fetchProperty(prop string) (map[rune]bool, error) {
	resp, err := http.Get(dataURL)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", dataURL, resp.Status)
	}

	set := make(map[rune]bool)
	sc := bufio.NewScanner(resp.Body)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		fields := strings.Split(line, ";")
		if len(fields) < 2 || strings.TrimSpace(fields[1]) != prop {
			continue
		}
		lo, hi, err := parseRange(strings.TrimSpace(fields[0]))
		if err != nil {
			return nil, err
		}
		for r := lo; r <= hi; r++ {
			set[r] = true
		}
	}
	return set, sc.Err()
}

// parseRange parses "1F600" or "1F600..1F64F" into an inclusive rune range.
func parseRange(s string) (lo, hi rune, err error) {
	a, b, ok := strings.Cut(s, "..")
	l, err := strconv.ParseInt(a, 16, 32)
	if err != nil {
		return 0, 0, err
	}
	if !ok {
		return rune(l), rune(l), nil
	}
	h, err := strconv.ParseInt(b, 16, 32)
	if err != nil {
		return 0, 0, err
	}
	return rune(l), rune(h), nil
}
